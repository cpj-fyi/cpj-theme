(function () {
    'use strict';

    function initReadingState() {
        const root = document.querySelector('[data-reading-state]');
        if (!root || root.dataset.readingReady) return;

        const memberId = (root.dataset.memberId || '').trim();
        const button = root.querySelector('[data-reading-toggle]');
        const label = root.querySelector('[data-reading-label]');
        const status = root.querySelector('[data-reading-status]');
        if (!memberId || !button || !label || !status) return;

        function chapterPath(href) {
            if (typeof href !== 'string' || !href) return null;
            try {
                const url = new URL(href, window.location.href);
                if (url.origin !== window.location.origin) return null;
                // Ghost chapter URLs treat a final slash as optional; query strings
                // and fragments should not create separate reading records.
                return url.pathname.replace(/\/+$/, '') || '/';
            } catch (_) {
                return null;
            }
        }

        const currentPath = chapterPath(root.dataset.chapterUrl);
        if (!currentPath) return;
        const prefix = 'cpj:reading:v1:' + encodeURIComponent(memberId) + ':';
        const storageKey = path => prefix + encodeURIComponent(path);
        const links = [...document.querySelectorAll('.chapter-list-link, .mobile-chapter-nav .chapter-btn')]
            .map(link => ({ link, path: chapterPath(link.getAttribute('href')) }))
            .filter(item => item.path);
        const originalLabels = new WeakMap();
        let isRead = false;

        function updateButton(value) {
            isRead = value;
            button.setAttribute('aria-pressed', String(value));
            label.textContent = value ? 'Mark as unread' : 'Mark as read';
        }

        function updateLink(link, value) {
            link.classList.toggle('is-read', value);
            let mark = link.querySelector('[data-chapter-read-mark]');
            if (value && !mark) {
                originalLabels.set(link, link.getAttribute('aria-label') || link.textContent.trim());
                mark = document.createElement('span');
                mark.className = 'chapter-read-mark';
                mark.setAttribute('data-chapter-read-mark', '');
                mark.setAttribute('aria-hidden', 'true');
                mark.textContent = '✓';
                // Preserve any title or shape markup generated by the chapter nav.
                link.append(mark);
            }
            if (mark) {
                mark.hidden = !value;
                // Preserve existing accessible labels while exposing read status.
                link.setAttribute('aria-label', originalLabels.get(link) + (value ? ', read' : ''));
            }
        }

        function refresh() {
            try {
                const storage = window.localStorage;
                const nextRead = storage.getItem(storageKey(currentPath)) === 'read';
                const linkStates = links.map(item => storage.getItem(storageKey(item.path)) === 'read');
                updateButton(nextRead);
                links.forEach((item, index) => updateLink(item.link, linkStates[index]));
                status.textContent = 'Saved on this browser';
                root.classList.remove('has-storage-error');
                button.disabled = false;
                return true;
            } catch (_) {
                status.textContent = 'Reading status is unavailable in this browser.';
                root.classList.add('has-storage-error');
                button.disabled = true;
                return false;
            }
        }

        button.addEventListener('click', function () {
            const nextRead = !isRead;
            try {
                const storage = window.localStorage;
                if (nextRead) storage.setItem(storageKey(currentPath), 'read');
                else storage.removeItem(storageKey(currentPath));
                refresh();
            } catch (_) {
                status.textContent = 'Couldn’t save on this browser. Your reading status hasn’t changed.';
                root.classList.add('has-storage-error');
            }
        });

        // Keep other tabs in this browser in sync without sending reader data.
        window.addEventListener('storage', function (event) {
            if (event.key === null || event.key.startsWith(prefix)) refresh();
        });
        window.addEventListener('pageshow', refresh);
        root.dataset.readingReady = 'true';
        refresh();
        root.hidden = false;
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initReadingState, { once: true });
    } else {
        initReadingState();
    }
})();
